#!/usr/bin/env node
// Convert the supplied PNG to a small flash-resident RGB565 firmware asset.
// This avoids keeping a PNG decoder or a full framebuffer in the Core2's heap.
const fs = require('node:fs');
const path = require('node:path');
const { PNG } = require('pngjs');
const source = PNG.sync.read(fs.readFileSync(path.join(__dirname, 'assets/astronaut.png')));
let left=source.width, top=source.height, right=-1, bottom=-1;
for (let y=0;y<source.height;y++) for (let x=0;x<source.width;x++) {
  if (source.data[(y*source.width+x)*4+3]>0) {
    left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x);bottom=Math.max(bottom,y);
  }
}
if (right<left) throw new Error('Source image has no visible pixels');
const width=156, height=184;
const scale=Math.min(width/(right-left+1),height/(bottom-top+1));
const drawWidth=(right-left+1)*scale, drawHeight=(bottom-top+1)*scale;
const offsetX=(width-drawWidth)/2, offsetY=(height-drawHeight)/2;
const pixels=[];
for (let y=0;y<height;y++) for (let x=0;x<width;x++) {
  const sx=left+(x-offsetX+0.5)/scale-0.5,sy=top+(y-offsetY+0.5)/scale-0.5;
  let rgb=[0,0,0];
  if(x>=offsetX&&x<offsetX+drawWidth&&y>=offsetY&&y<offsetY+drawHeight){
    const ix=Math.floor(sx),iy=Math.floor(sy),fx=sx-ix,fy=sy-iy;
    for(let j=0;j<2;j++)for(let i=0;i<2;i++){
      const px=Math.max(0,Math.min(source.width-1,ix+i)),py=Math.max(0,Math.min(source.height-1,iy+j));
      const index=(py*source.width+px)*4;
      const weight=(i?fx:1-fx)*(j?fy:1-fy)*source.data[index+3]/255;
      for(let c=0;c<3;c++)rgb[c]+=source.data[index+c]*weight;
    }
  }
  const [r,g,b]=rgb.map(Math.round);
  pixels.push(((r>>3)<<11)|((g>>2)<<5)|(b>>3));
}
const lines=[];
for(let i=0;i<pixels.length;i+=16)lines.push('  '+pixels.slice(i,i+16).map(v=>'0x'+v.toString(16).padStart(4,'0')).join(', ')+',');
const output=`// Generated by hardware/generate-charm-art.cjs from the supplied astronaut PNG.\n#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\nnamespace charm_art {\nconstexpr int kWidth=${width};\nconstexpr int kHeight=${height};\nstatic const uint16_t kAstronaut[] PROGMEM = {\n${lines.join('\n')}\n};\n}\n`;
fs.writeFileSync(path.join(__dirname,'core2-badge/astronaut_rgb565.h'),output);
console.log(`Prepared ${width}x${height} RGB565 asset (${pixels.length*2} flash bytes, no image decode heap).`);
